from __future__ import annotations

import math


def _star(cx: float, cy: float, outer: float, inner: float, points: int) -> str:
    coords = []
    for i in range(2 * points):
        r = outer if i % 2 == 0 else inner
        a = math.radians(-90 + 180 * i / points)
        coords.append(f"{cx + r * math.cos(a):.2f} {cy + r * math.sin(a):.2f}")
    return "M" + " L".join(coords) + " Z"


def _dot(cx: float, cy: float, r: float) -> str:
    return (
        f"M{cx - r:.2f} {cy:.2f} A{r} {r} 0 1 0 {cx + r:.2f} {cy:.2f} A{r} {r} 0 1 0 {cx - r:.2f} {cy:.2f} Z"
    )


def _ring(cx: float, cy: float, r: float, n: int, dot: float) -> str:
    return " ".join(
        _dot(cx + r * math.cos(2 * math.pi * i / n), cy + r * math.sin(2 * math.pi * i / n), dot)
        for i in range(n)
    )


def _foot(cx: float, cy: float) -> str:
    toes = " ".join(_dot(cx + dx, cy - 5.4 + abs(dx) * 0.5, 1.0) for dx in (-1.9, 0, 1.9))
    return f"{_dot(cx, cy, 2.9).replace('A2.9 2.9', 'A2.9 4.1')} {toes}"



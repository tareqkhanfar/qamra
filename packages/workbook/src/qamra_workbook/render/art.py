def stars(count: int, css_class: str = "stars", fill: str = GOLD, edge: str = GOLD_EDGE) -> Markup:
    """`count` filled stars in a row (the ⭐ / ⭐⭐ levels), drawn so no emoji font is needed."""
    body = "".join(
        f'<path d="{star_points(6 + 12 * i, 6.3, 5.6, 2.5)}" fill="{fill}" stroke="{edge}" '
        'stroke-width="0.9" stroke-linejoin="round"/>'
        for i in range(count)
    )
    return Markup(  # nosec B704 (static art)
        f'<svg class="{css_class}" viewBox="0 0 {12 * count} 12" aria-hidden="true">{body}</svg>'
    )
